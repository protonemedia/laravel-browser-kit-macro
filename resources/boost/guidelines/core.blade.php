## Laravel Browser Kit Macro

- `protonemedia/laravel-browser-kit-macro` adds a `browserKit()` macro to `TestResponse`, enabling BrowserKit-style DOM assertions in Laravel feature tests.
- Always activate the `laravel-browser-kit-macro-development` skill when working with BrowserKit assertions, the `browserKit()` macro, or any test code that uses `ProtoneMedia\LaravelBrowserKitMacro`.
